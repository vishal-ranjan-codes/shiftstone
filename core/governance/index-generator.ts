/**
 * OKF index generator (amendment C5) — an `index.md` at the docs root and in
 * every subdirectory, so loaders read an index first and never crawl.
 *
 *   node core/governance/index.js           regenerate all indexes
 *   node core/governance/index.js --check   CI: fail on missing/stale indexes
 *
 * Indexes are deterministic: the frontmatter timestamp is preserved on
 * regeneration, so --check only fails when the listed content changed.
 */

import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { parse as parseYaml, stringify as stringifyYaml } from 'yaml';

const SKIP_DIRS = new Set(['node_modules', '.git', '.loops', 'dist', 'build', 'coverage']);

export interface IndexCheckResult {
  missing: string[];
  stale: string[];
  generated: string[];
}

function parseFrontmatter(raw: string): Record<string, unknown> {
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(raw);
  if (!match) return {};
  try {
    return (parseYaml(match[1]) ?? {}) as Record<string, unknown>;
  } catch {
    return {};
  }
}

function titleOf(raw: string, fallback: string): string {
  const data = parseFrontmatter(raw);
  if (typeof data['title'] === 'string' && data['title'].trim().length > 0) return data['title'];
  const heading = /^#\s+(.+)$/m.exec(raw);
  if (heading) return heading[1].trim();
  return fallback.replace(/\.md$/, '');
}

export function normalizeIndex(content: string): string {
  return content.replace(/^timestamp:\s*\S+.*$/m, 'timestamp: <preserved>').replace(/\r\n/g, '\n');
}

export async function collectIndexableDirs(root: string): Promise<string[]> {
  const out: string[] = [];
  const walk = async (dir: string): Promise<boolean> => {
    let hasMd = false;
    let entries;
    try {
      entries = await readdir(dir, { withFileTypes: true });
    } catch {
      return false;
    }
    for (const entry of entries) {
      if (entry.isDirectory() && SKIP_DIRS.has(entry.name)) continue;
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        const childHas = await walk(full);
        hasMd = hasMd || childHas;
      } else if (entry.name.endsWith('.md') && entry.name !== 'index.md') {
        hasMd = true;
      }
    }
    if (hasMd) out.push(dir);
    return hasMd;
  };
  await walk(root);
  return out.sort((a, b) => b.split(path.sep).length - a.split(path.sep).length); // deepest first
}

export async function renderIndex(dir: string): Promise<string | null> {
  const entries = await readdir(dir, { withFileTypes: true });
  const files: { name: string; title: string }[] = [];
  const dirs: string[] = [];
  for (const entry of entries) {
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      const hasIndex = await readdir(path.join(dir, entry.name)).then(
        (list) => list.includes('index.md'),
        () => false,
      );
      if (hasIndex) dirs.push(entry.name);
    } else if (entry.name.endsWith('.md') && entry.name !== 'index.md') {
      const raw = await readFile(path.join(dir, entry.name), 'utf8');
      files.push({ name: entry.name, title: titleOf(raw, entry.name) });
    }
  }
  if (files.length === 0 && dirs.length === 0) return null;

  files.sort((a, b) => a.name.localeCompare(b.name));
  dirs.sort();

  const existing = await readFile(path.join(dir, 'index.md'), 'utf8').catch(() => null);
  const timestamp = existing
    ? (parseFrontmatter(existing)['timestamp'] as string | undefined) ?? new Date().toISOString()
    : new Date().toISOString();
  const dirName = path.basename(dir);

  const lines = [
    '---',
    stringifyYaml({ type: 'index', timestamp }).trimEnd(),
    '---',
    '',
    `# ${dirName === 'docs' ? 'docs' : dirName} — Index`,
    '',
    '> Generated by `node core/governance/index.js` — read an index first; never crawl a directory.',
    '',
  ];
  if (dirs.length > 0) {
    lines.push('**Subdirectories**', '');
    for (const sub of dirs) lines.push(`- [${sub}/](./${sub}/index.md)`);
    lines.push('');
  }
  if (files.length > 0) {
    lines.push('**Files**', '');
    for (const file of files) lines.push(`- [${file.title}](./${file.name})`);
    lines.push('');
  }
  return lines.join('\n');
}

export async function generateAll(root: string): Promise<IndexCheckResult> {
  const result: IndexCheckResult = { missing: [], stale: [], generated: [] };
  const dirs = await collectIndexableDirs(root);
  for (const dir of dirs) {
    const rendered = await renderIndex(dir);
    if (rendered === null) continue;
    const indexPath = path.join(dir, 'index.md');
    const existing = await readFile(indexPath, 'utf8').catch(() => null);
    if (existing === null) {
      result.missing.push(path.relative(root, indexPath));
      await writeFile(indexPath, rendered, 'utf8');
      result.generated.push(path.relative(root, indexPath));
    } else if (normalizeIndex(existing) !== normalizeIndex(rendered)) {
      result.stale.push(path.relative(root, indexPath));
      await writeFile(indexPath, rendered, 'utf8');
      result.generated.push(path.relative(root, indexPath));
    }
  }
  return result;
}

/** CI mode: report missing/stale WITHOUT writing. */
export async function checkAll(root: string): Promise<IndexCheckResult> {
  const result: IndexCheckResult = { missing: [], stale: [], generated: [] };
  const dirs = await collectIndexableDirs(root);
  for (const dir of dirs) {
    const rendered = await renderIndex(dir);
    if (rendered === null) continue;
    const indexPath = path.join(dir, 'index.md');
    const existing = await readFile(indexPath, 'utf8').catch(() => null);
    const rel = path.relative(root, indexPath);
    if (existing === null) result.missing.push(rel);
    else if (normalizeIndex(existing) !== normalizeIndex(rendered)) result.stale.push(rel);
  }
  return result;
}

/**
 * Shallow (non-recursive) index for a knowledge-bundle root that lives
 * outside `docs/` — `packs/`, `.agents/skills/` (Phase 6.7 exit criterion:
 * every bundle carries an `index.md` + `log.md`). Only the bundle ROOT is
 * indexed: skill and pack subdirectories keep their own catalogs (the skills
 * manifest / pack registry — blueprint §6.6 forbids a second skill index).
 */
export async function generateOne(
  dir: string,
  opts?: { write?: boolean },
): Promise<{ missing: boolean; stale: boolean; written: boolean; skipped: boolean }> {
  const write = opts?.write ?? true;
  const rendered = await renderIndex(dir);
  if (rendered === null) return { missing: false, stale: false, written: false, skipped: true };
  const indexPath = path.join(dir, 'index.md');
  const existing = await readFile(indexPath, 'utf8').catch(() => null);
  if (existing === null) {
    if (write) await writeFile(indexPath, rendered, 'utf8');
    return { missing: true, stale: false, written: write, skipped: false };
  }
  const stale = normalizeIndex(existing) !== normalizeIndex(rendered);
  if (stale && write) await writeFile(indexPath, rendered, 'utf8');
  return { missing: false, stale, written: stale && write, skipped: false };
}
