#!/usr/bin/env node
/**
 * quality-flywheel-loop turn script (amendment B5) — the continuous quality
 * flywheel: run the eval suites → cluster failures by their `cluster` label →
 * open one backlog item per uncovered cluster → regression-verify on fix.
 *
 *   node .shiftstone/harness/evals/flywheel.js                 turn: run + cluster + propose
 *   node .shiftstone/harness/evals/flywheel.js --verify        gate: runs the suites, then
 *                                                       every failing case covered?
 *   node .shiftstone/harness/evals/flywheel.js --list-failures enumerate: run + failing case ids
 *   node .shiftstone/harness/evals/flywheel.js --root <dir>    workspace root (tests)
 *
 * All three modes run the eval suites first (the flywheel's first move is
 * always "run the evals").
 *
 * Exit codes (turn): 0 = progress (clusters proposed / all covered), 78 = blocked.
 * The proposals ledger lives at .loops/quality-flywheel-loop/backlog-proposals.md
 * (runtime state); promotion into docs/backlog/ is a human-gated step.
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { latestOutcomes, runEvals } from './runner.ts';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DEFAULT_ROOT = path.resolve(HERE, '..', '..', '..');
const LEDGER_REL = path.join('.loops', 'quality-flywheel-loop', 'backlog-proposals.md');

function argValue(argv, flag) {
  const index = argv.indexOf(flag);
  return index >= 0 ? argv[index + 1] : undefined;
}

async function latestFailures(root) {
  const resultsFile = path.join(root, 'evals', 'runs.jsonl');
  const latest = await latestOutcomes(resultsFile);
  return [...latest.values()].filter((row) => !row.skipped && !row.passed);
}

function coveredCaseIds(ledgerText) {
  const covered = new Set();
  for (const line of ledgerText.split(/\r?\n/)) {
    const match = /^- Cases:\s*(.+)$/.exec(line.trim());
    if (!match) continue;
    for (const id of match[1].split(',').map((s) => s.trim()).filter(Boolean)) covered.add(id);
  }
  return covered;
}

function renderCluster(cluster, caseIds, timestamp) {
  const lines = [
    `## [ ] Cluster: ${cluster} — opened ${timestamp}`,
    `- Cases: ${caseIds.join(', ')}`,
    '- [ ] Root-cause the failure(s) in this cluster and fix them',
    '- [ ] Regression-verify: re-run `node .shiftstone/harness/evals/run.js --strict` green after the fix',
    '- [ ] Promote this item into `docs/backlog/` after human review',
    '',
  ];
  return lines.join('\n');
}

export async function main(argv = process.argv.slice(2)) {
  const root = path.resolve(argValue(argv, '--root') ?? DEFAULT_ROOT);
  const ledgerPath = path.join(root, LEDGER_REL);
  const verify = argv.includes('--verify');
  const list = argv.includes('--list-failures');

  // Every mode starts by running the suites — the flywheel's first move is
  // always "run the evals" (B5), and a fresh workspace must not be vacuously green.
  try {
    const report = await runEvals({ root });
    if (!verify && !list) {
      const failedNow = report.suites.reduce((n, s) => n + s.failed, 0);
      console.log(`flywheel: eval suites run — ${failedNow} failing case(s)`);
    }
  } catch (error) {
    const message = `eval runner failed — ${error instanceof Error ? error.message : String(error)}`;
    if (list) {
      console.error(message);
      return 1;
    }
    if (verify) {
      console.error(`unverifiable: ${message}`);
      return 1;
    }
    console.error(`blocked: ${message}`);
    return 78;
  }

  const failures = await latestFailures(root);

  if (list) {
    for (const row of failures) console.log(row.case_id);
    return 0;
  }

  if (verify) {
    let ledger = '';
    try {
      ledger = await readFile(ledgerPath, 'utf8');
    } catch {
      // no ledger yet — nothing has been proposed
    }
    const covered = coveredCaseIds(ledger);
    const uncovered = failures.filter((row) => !covered.has(row.case_id));
    if (uncovered.length > 0) {
      console.error(
        `uncovered eval failure(s): ${uncovered.map((r) => `${r.suite}/${r.case_id}`).join(', ')}`,
      );
      return 1;
    }
    console.log(
      failures.length === 0
        ? 'flywheel: no failing eval cases — nothing to cluster'
        : `flywheel: all ${failures.length} failing case(s) covered by open backlog items`,
    );
    return 0;
  }

  // ---- turn: cluster fresh failures and open one backlog item per cluster ----
  if (failures.length === 0) {
    console.log('flywheel: suite is green — no clusters to open');
    return 0;
  }

  let ledger = '';
  try {
    ledger = await readFile(ledgerPath, 'utf8');
  } catch {
    ledger = [
      '# quality-flywheel-loop — backlog proposals',
      '',
      '> Generated by `node .shiftstone/harness/evals/flywheel.js` (B5). Promote clusters',
      '> into `docs/backlog/` after human review; this ledger is the run history.',
      '',
    ].join('\n');
  }
  const covered = coveredCaseIds(ledger);
  const timestamp = new Date().toISOString();

  const newByCluster = new Map();
  for (const row of failures) {
    if (covered.has(row.case_id)) continue;
    const cluster = row.cluster || 'unlabeled';
    if (!newByCluster.has(cluster)) newByCluster.set(cluster, []);
    newByCluster.get(cluster).push(row.case_id);
  }

  let additions = '';
  for (const [cluster, caseIds] of [...newByCluster.entries()].sort()) {
    additions += `${renderCluster(cluster, caseIds, timestamp)}\n`;
    console.log(`opened backlog item for cluster "${cluster}" (${caseIds.length} case(s))`);
  }
  if (additions) {
    await mkdir(path.dirname(ledgerPath), { recursive: true });
    await writeFile(ledgerPath, `${ledger.replace(/\s*$/, '')}\n\n${additions}`, 'utf8');
  }

  // Every currently failing case is now covered (previously or just now) —
  // report them as addressed so the enumeration gate (A4) can close.
  for (const row of failures) console.log(`ADDRESSED: ${row.case_id}`);
  return 0;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  process.exitCode = await main();
}
