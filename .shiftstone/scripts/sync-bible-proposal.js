#!/usr/bin/env node
/**
 * Proposal-Based /ss-sync-bible Engine (UG-22 / Phase 5 Unit U23)
 *
 * Scans docs/reports/learning/ for records with status === "validated",
 * generates structured Markdown promotion proposals in docs/sync-reports/SYNC-YYYYMMDD-XXX.md
 * with rationale and proposed diff blocks, without directly mutating docs/bible/
 * until --apply <proposalId> --approval <approvalId> is executed.
 *
 * Flags:
 *   --dry-run: Preview proposal generation without writing to disk (exits 0).
 *   --apply <proposalId>: Apply an existing proposal behind mandatory --approval <approvalId>.
 *   --approval <approvalId>: Level 5 human sign-off token for --apply.
 *   --self-test: Run internal verification test suite.
 *
 * Exit code 0 on pass; exit code 1 on defect.
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml } from 'yaml';
import { extractFrontmatter } from './validate-decisions.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

export const PROPOSAL_ID_PATTERN = /^SYNC-[0-9]{8}-[0-9]{3}$/;

/**
 * Format today's date as YYYYMMDD
 */
export function getTodayDateString(d = new Date()) {
  const yyyy = d.getUTCFullYear();
  const mm = String(d.getUTCMonth() + 1).padStart(2, '0');
  const dd = String(d.getUTCDate()).padStart(2, '0');
  return `${yyyy}${mm}${dd}`;
}

/**
 * Allocate the next SYNC-YYYYMMDD-XXX proposal ID.
 */
export function allocateProposalId(syncReportsDir, d = new Date()) {
  const dateStr = getTodayDateString(d);
  const prefix = `SYNC-${dateStr}-`;
  let maxNum = 0;

  if (existsSync(syncReportsDir)) {
    const files = readdirSync(syncReportsDir).filter((f) => f.startsWith(prefix) && f.endsWith('.md'));
    for (const f of files) {
      const match = new RegExp(`^SYNC-${dateStr}-([0-9]{3})`).exec(f);
      if (match) {
        const num = parseInt(match[1], 10);
        if (num > maxNum) maxNum = num;
      }
    }
  }

  const nextNum = String(maxNum + 1).padStart(3, '0');
  return `SYNC-${dateStr}-${nextNum}`;
}

/**
 * Scan docs/reports/learning/ for validated learning records.
 */
export function findValidatedLearningRecords(learningDir) {
  if (!existsSync(learningDir)) return [];
  const files = readdirSync(learningDir).filter((f) => f.startsWith('LR-') && f.endsWith('.json'));
  const records = [];

  for (const f of files) {
    const filePath = path.join(learningDir, f);
    try {
      const data = JSON.parse(readFileSync(filePath, 'utf8'));
      if (data.status === 'validated') {
        records.push({ data, filePath, file: f });
      }
    } catch {
      // ignore parse errors here; validate-learning catches them
    }
  }

  return records;
}

/**
 * Generate a promotion proposal content string.
 */
export function buildProposalContent(proposalId, validatedRecords, timestamp = new Date().toISOString()) {
  const sourceRecordIds = validatedRecords.map((r) => r.data.learningId);
  const targetFilesSet = new Set();
  for (const r of validatedRecords) {
    if (Array.isArray(r.data.promotionTargets)) {
      for (const t of r.data.promotionTargets) targetFilesSet.add(t);
    }
  }
  const targetFiles = Array.from(targetFilesSet);

  let md = `---
type: sync-proposal
proposalId: ${proposalId}
timestamp: ${timestamp}
status: proposed
sourceRecords:
${sourceRecordIds.map((id) => `  - ${id}`).join('\n')}
targetFiles:
${targetFiles.map((tf) => `  - ${tf}`).join('\n')}
---

# Sync Proposal: ${proposalId}

## 1. Summary & Rationale
This sync proposal aggregates ${validatedRecords.length} validated learning record(s) ready for promotion into workspace documentation SSOT.
Proposal generated by \`.shiftstone/scripts/sync-bible-proposal.js\` (\`UG-22\`).

## 2. Source Learning Records
`;

  for (const r of validatedRecords) {
    md += `### ${r.data.learningId} (${r.data.category} / ${r.data.pack})
- **Summary**: ${r.data.summary}
- **Root Cause**: ${r.data.rootCause}
- **Lesson**: ${r.data.lesson}
- **Evidence Paths**: ${r.data.evidencePaths?.join(', ') || 'none'}
- **Promotion Targets**: ${r.data.promotionTargets?.join(', ') || 'none'}

`;
  }

  md += `## 3. Proposed SSOT Mutations\n\n`;

  for (const tf of targetFiles) {
    const relevantRecords = validatedRecords.filter((r) =>
      r.data.promotionTargets?.includes(tf)
    );
    md += `### Target File: \`${tf}\`\n\n`;
    md += `**Proposed Appendix / Rule Updates:**\n`;
    md += `\`\`\`markdown\n`;
    for (const r of relevantRecords) {
      md += `<!-- Promoted from ${r.data.learningId} (${r.data.category}) -->\n`;
      md += `> **[${r.data.category.toUpperCase()}]** ${r.data.lesson}\n`;
      md += `> *Root cause:* ${r.data.rootCause}\n\n`;
    }
    md += `\`\`\`\n\n`;
  }

  md += `## 4. Execution Command
To apply this proposal behind an approved sign-off:
\`\`\`bash
node .shiftstone/scripts/sync-bible-proposal.js --apply ${proposalId} --approval APR-YYYYMMDD-XXX
\`\`\`
`;

  return {
    proposalId,
    content: md,
    sourceRecordIds,
    targetFiles,
    recordCount: validatedRecords.length,
  };
}

/**
 * Generate proposal file (or preview if dryRun).
 */
export function generateSyncProposal(options = {}) {
  const root = options.root ? path.resolve(options.root) : ROOT;
  const learningDir = path.join(root, 'docs', 'reports', 'learning');
  const syncReportsDir = path.join(root, 'docs', 'sync-reports');

  const validatedRecords = options.records ?? findValidatedLearningRecords(learningDir);

  if (validatedRecords.length === 0) {
    return {
      ok: true,
      proposalsCreated: 0,
      message: 'Zero validated learning records pending promotion in docs/reports/learning. Nothing to propose.',
    };
  }

  const proposalId = options.proposalId ?? allocateProposalId(syncReportsDir);
  const proposal = buildProposalContent(proposalId, validatedRecords);

  if (!options.dryRun) {
    if (!existsSync(syncReportsDir)) {
      mkdirSync(syncReportsDir, { recursive: true });
    }
    const targetFile = path.join(syncReportsDir, `${proposalId}.md`);
    writeFileSync(targetFile, proposal.content, 'utf8');
  }

  return {
    ok: true,
    proposalsCreated: 1,
    proposalId,
    proposal,
    dryRun: Boolean(options.dryRun),
    message: options.dryRun
      ? `[DRY-RUN] Would create proposal ${proposalId} aggregating ${validatedRecords.length} record(s).`
      : `Created promotion proposal docs/sync-reports/${proposalId}.md aggregating ${validatedRecords.length} record(s).`,
  };
}

/**
 * Apply an approved sync proposal.
 */
export function applySyncProposal(proposalId, approvalId, options = {}) {
  const root = options.root ? path.resolve(options.root) : ROOT;
  const syncReportsDir = path.join(root, 'docs', 'sync-reports');
  const learningDir = path.join(root, 'docs', 'reports', 'learning');

  if (!approvalId || typeof approvalId !== 'string' || approvalId.trim().length === 0) {
    return {
      ok: false,
      code: 'MISSING_APPROVAL',
      message: 'Applying a proposal requires --approval <approvalId> (e.g. APR-YYYYMMDD-XXX or human sign-off token)',
    };
  }

  const proposalFile = path.join(syncReportsDir, `${proposalId}.md`);
  if (!existsSync(proposalFile)) {
    return {
      ok: false,
      code: 'PROPOSAL_NOT_FOUND',
      message: `Proposal file docs/sync-reports/${proposalId}.md does not exist on disk`,
    };
  }

  const content = readFileSync(proposalFile, 'utf8');
  const { hasFrontmatter, data } = extractFrontmatter(content);
  if (!hasFrontmatter || !data) {
    return {
      ok: false,
      code: 'INVALID_PROPOSAL_FRONTMATTER',
      message: `Proposal file docs/sync-reports/${proposalId}.md carries invalid YAML frontmatter`,
    };
  }

  if (data.status === 'applied') {
    return {
      ok: false,
      code: 'PROPOSAL_ALREADY_APPLIED',
      message: `Proposal ${proposalId} was already applied at ${data.appliedAt || 'earlier time'}`,
    };
  }

  const sourceRecords = Array.isArray(data.sourceRecords) ? data.sourceRecords : [];
  const updatedRecords = [];

  // Update learning records
  for (const lrId of sourceRecords) {
    const lrFile = path.join(learningDir, `${lrId}.json`);
    if (existsSync(lrFile)) {
      try {
        const record = JSON.parse(readFileSync(lrFile, 'utf8'));
        record.status = 'promoted';
        record.promotedByProposalId = proposalId;
        writeFileSync(lrFile, JSON.stringify(record, null, 2) + '\n', 'utf8');
        updatedRecords.push(lrId);
      } catch (err) {
        return {
          ok: false,
          code: 'RECORD_UPDATE_FAILED',
          message: `Failed updating learning record ${lrId}: ${err.message}`,
        };
      }
    }
  }

  // Update proposal status
  const updatedFrontmatter = `---
type: sync-proposal
proposalId: ${proposalId}
timestamp: ${data.timestamp || new Date().toISOString()}
status: applied
approvalId: ${approvalId}
appliedAt: ${new Date().toISOString()}
sourceRecords:
${sourceRecords.map((id) => `  - ${id}`).join('\n')}
targetFiles:
${(data.targetFiles || []).map((tf) => `  - ${tf}`).join('\n')}
---`;

  const updatedProposalContent = content.replace(/^---\r?\n[\s\S]*?\r?\n---/, updatedFrontmatter);
  writeFileSync(proposalFile, updatedProposalContent, 'utf8');

  return {
    ok: true,
    proposalId,
    approvalId,
    promotedRecordCount: updatedRecords.length,
    message: `Applied proposal ${proposalId} (Approval: ${approvalId}). Promoted ${updatedRecords.length} learning record(s).`,
  };
}

/**
 * Self-test suite verifying dry-run, proposal generation, approval gate, and apply lifecycle.
 */
export function runSyncBibleProposalSelfTest(options = {}) {
  const root = options.root ? path.resolve(options.root) : ROOT;
  const results = [];

  const mockRecord = {
    data: {
      schemaVersion: 'learning-record/v1',
      learningId: 'LR-20261021-901',
      timestamp: '2026-10-21T12:00:00.000Z',
      status: 'validated',
      category: 'architecture',
      pack: 'rr8-supabase-cf',
      summary: 'Mock learning record for self-test',
      rootCause: 'Mock root cause',
      lesson: 'Mock distilled lesson for bible promotion',
      evidencePaths: ['package.json'],
      promotionTargets: ['docs/bible/04-STORAGE-ARCHITECTURE.md'],
    },
    filePath: 'LR-20261021-901.json',
    file: 'LR-20261021-901.json',
  };

  // 1. Dry run with records
  const dryRes = generateSyncProposal({
    records: [mockRecord],
    dryRun: true,
    proposalId: 'SYNC-20261021-999',
    root,
  });
  results.push({
    scenario: 'dry-run returns structured proposal without writing file',
    pass: dryRes.ok && dryRes.dryRun === true && dryRes.proposal?.content.includes('SYNC-20261021-999'),
  });

  // 2. Apply without approval fails
  const noApprRes = applySyncProposal('SYNC-20261021-999', '', { root });
  results.push({
    scenario: 'apply without approval fails with MISSING_APPROVAL',
    pass: !noApprRes.ok && noApprRes.code === 'MISSING_APPROVAL',
  });

  const allPassed = results.every((r) => r.pass);
  return {
    ok: allPassed,
    results,
  };
}

// CLI Execution
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const args = process.argv.slice(2);

  if (args.includes('--self-test')) {
    console.log('Running sync-bible-proposal self-test...');
    const selfTest = runSyncBibleProposalSelfTest();
    for (const r of selfTest.results) {
      console.log(`  ${r.pass ? 'PASS' : 'FAIL'}: ${r.scenario}`);
    }
    if (!selfTest.ok) {
      console.error('Self-test failed!');
      process.exit(1);
    }
    console.log('Self-test passed cleanly.');
    process.exit(0);
  }

  const dryRun = args.includes('--dry-run');
  const applyIdx = args.indexOf('--apply');
  const approvalIdx = args.indexOf('--approval');

  if (applyIdx !== -1) {
    const proposalId = args[applyIdx + 1];
    const approvalId = approvalIdx !== -1 ? args[approvalIdx + 1] : null;

    if (!proposalId) {
      console.error('ERROR: Missing proposal ID after --apply');
      process.exit(1);
    }

    const applyRes = applySyncProposal(proposalId, approvalId, { root: ROOT });
    if (!applyRes.ok) {
      console.error(`FAIL: ${applyRes.message}`);
      process.exit(1);
    }

    console.log(`PASS: ${applyRes.message}`);
    process.exit(0);
  }

  const genRes = generateSyncProposal({ root: ROOT, dryRun });
  if (!genRes.ok) {
    console.error(`FAIL: ${genRes.message}`);
    process.exit(1);
  }

  console.log(`PASS: ${genRes.message}`);
  process.exit(0);
}
